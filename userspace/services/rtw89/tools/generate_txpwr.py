#!/usr/bin/env python3
"""Generate rtw89.drv's transmit power tables (docs/wifi.md, D7; W3).

Reads Linux rtw89's rtw8852b_table.c (GPL-2.0 OR BSD-3-Clause, Copyright
Realtek Corporation; taken under BSD-3-Clause) at the pinned revision (the
one generate_tables.py pins) and writes the Ada spec RTW89_TX_Power_8852B:

- the power-by-rate configuration (rtw89_8852b_txpwr_byrate), as shipped;
- the worldwide (RTW89_WW) power limits for 20 and 40 MHz, per band,
  transmit-path count, rate section (CCK, OFDM, MCS), beamforming and
  channel index (rtw89_8852b_txpwr_lmt_2g / _5g); absent entries are 0,
  as in C.

CuBit uses the worldwide limits only: they are the lowest of every
regulation's, so they hold wherever the laptop is. Units are Realtek's RF
units (1/4 dBm), signed octets.

Usage: generate_txpwr.py <rtw8852b_table.c> <output .ads>
       generate_txpwr.py --check <rtw8852b_table.c> <existing .ads>
"""
import hashlib
import re
import sys

LINUX_COMMIT = '17bb0e2f6c8043f70a693a5f3797471cbed354c8'
PINNED_SHA256 = 'bcee2f4357f6ada16c831f460edc5e00c5471a79333b606e36cfa0b630352d09'

BW_KEPT = 2           # RTW89_CHANNEL_WIDTH_20, _40
NTX = 2               # RTW89_NTX_NUM
RS_LMT = 3            # CCK, OFDM, MCS (RTW89_RS_LMT_NUM)
BF = 2                # RTW89_BF_NUM
CH_2G = 14            # RTW89_2G_CH_NUM
CH_5G = 53            # RTW89_5G_CH_NUM

BYRATE = re.compile(r'\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(0x[0-9A-Fa-f]+),\s*\}')
LIMIT = re.compile(r'\[(\d+)\]\[(\d+)\]\[(\d+)\]\[(\d+)\]\[RTW89_WW\]\[(\d+)\]\s*=\s*(-?\d+),')


def section(source, start_pattern):
    start = re.search(start_pattern, source)
    if not start:
        raise SystemExit('%s not found' % start_pattern)
    return source[start.end():source.index('};', start.end())]


def parse(source):
    byrate = [tuple(int(v, 0) for v in m) for m in BYRATE.findall(
        section(source, r'static const struct rtw89_txpwr_byrate_cfg rtw89_8852b_txpwr_byrate\[\] = \{'))]
    if not byrate:
        raise SystemExit('byrate table empty')
    limits = {}
    for band, name, channels in (('2G', 'rtw89_8852b_txpwr_lmt_2g', CH_2G), ('5G', 'rtw89_8852b_txpwr_lmt_5g', CH_5G)):
        table = [[[[[0] * channels for _ in range(BF)] for _ in range(RS_LMT)] for _ in range(NTX)]
                 for _ in range(BW_KEPT)]
        body = section(source, r'const s8 ' + name + r'\[[^=]*= \{')
        for bw, ntx, rs, bf, ch, value in LIMIT.findall(body):
            bw, ntx, rs, bf, ch, value = int(bw), int(ntx), int(rs), int(bf), int(ch), int(value)
            if bw < BW_KEPT:
                table[bw][ntx][rs][bf][ch] = value
        limits[band] = table
    return byrate, limits


def render(byrate, limits):
    out = []
    out.append('-' * 78)
    out.append('--  GENERATED by userspace/services/rtw89/tools/generate_txpwr.py: do not')
    out.append('--  edit. Source: Linux drivers/net/wireless/realtek/rtw89/rtw8852b_table.c')
    out.append('--  at commit %s' % LINUX_COMMIT)
    out.append('--  (SHA-256 %s).' % PINNED_SHA256)
    out.append('--')
    out.append('--  Copyright(c) 2019-2020 Realtek Corporation. Used under the BSD-3-Clause')
    out.append('--  option of its GPL-2.0 OR BSD-3-Clause licence (the notice is in')
    out.append('--  RTW89_Tables_8852B, generated from the same file).')
    out.append('-' * 78)
    out.append('pragma Ada_2022;')
    out.append('')
    out.append('package RTW89_TX_Power_8852B with Pure, SPARK_Mode is')
    out.append('')
    out.append('   --  rtw89_txpwr_byrate_cfg: band, nss, rate section, first index,')
    out.append('   --  count, up to four values (low octet first).')
    out.append('   type Byrate_Entry is record')
    out.append('      Band, NSS, Section, First, Count : Natural;')
    out.append('      Data : Natural;   --  32 bits, 0 .. 2 ** 32 - 1')
    out.append('   end record;')
    out.append('   type Byrate_Table is array (Positive range <>) of Byrate_Entry;')
    out.append('   Byrate : constant Byrate_Table (1 .. %d) :=' % len(byrate))
    rows = ['(%d, %d, %d, %d, %d, 16#%s_%s#)' % (b, n, r, s, l, ('%08X' % d)[:4], ('%08X' % d)[4:])
            for b, n, r, s, l, d in byrate]
    out.append('     [' + ',\n      '.join(rows) + '];')
    out.append('')
    out.append('   --  Worldwide limits, RF units (1/4 dBm), by row and channel index; the')
    out.append('   --  row is ((bandwidth * 2 + paths) * 3 + section) * 2 + beamforming:')
    out.append('   --  bandwidth 0 (20 MHz) or 1 (40 MHz), paths 0 (one) or 1 (two),')
    out.append('   --  section CCK, OFDM, MCS, beamforming off or on (Row).')
    out.append('   subtype Limit is Integer range -128 .. 127;')
    out.append('   Rows : constant := %d;' % (BW_KEPT * NTX * RS_LMT * BF))
    out.append('   function Row (Width, Paths, Section, BF : Natural) return Natural is')
    out.append('     (((Width * 2 + Paths) * 3 + Section) * 2 + BF)')
    out.append('   with Pre => Width <= 1 and then Paths <= 1 and then Section <= 2 and then BF <= 1,')
    out.append('        Post => Row\'Result < Rows;')
    for band, channels in (('2G', CH_2G), ('5G', CH_5G)):
        table = limits[band]
        out.append('   type Limits_%s is array (0 .. Rows - 1, 0 .. %d) of Limit;' % (band, channels - 1))
        out.append('   Limit_%s : constant Limits_%s :=' % (band, band))
        rows = []
        for bw in range(BW_KEPT):
            for ntx in range(NTX):
                for rs in range(RS_LMT):
                    for bf in range(BF):
                        values = table[bw][ntx][rs][bf]
                        chunks = [', '.join(str(v) for v in values[i:i + 14]) for i in range(0, len(values), 14)]
                        rows.append('[' + ',\n        '.join(chunks) + ']')
        out.append('     [' + ',\n      '.join(rows) + '];')
        out.append('')
    out.append('end RTW89_TX_Power_8852B;')
    return '\n'.join(out) + '\n'


def main(argv):
    check = len(argv) == 4 and argv[1] == '--check'
    if len(argv) != 3 and not check:
        raise SystemExit(__doc__)
    source_path, output_path = argv[-2], argv[-1]
    raw = open(source_path, 'rb').read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINNED_SHA256:
        raise SystemExit('%s: SHA-256 %s is not the pinned %s' % (source_path, digest, PINNED_SHA256))
    text = render(*parse(raw.decode()))
    if check:
        if open(output_path).read() != text:
            print('FAIL: %s differs from a fresh generation' % output_path)
            return 1
        print('PASS: %s matches a fresh generation' % output_path)
        return 0
    open(output_path, 'w').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
