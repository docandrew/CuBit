#!/usr/bin/env python3
"""Generate rtw89.drv's BB/RF initialisation tables (docs/wifi.md, D7).

Reads Linux rtw89's rtw8852b_table.c (GPL-2.0 OR BSD-3-Clause, Copyright
Realtek Corporation; taken under BSD-3-Clause) at the pinned revision and
writes the Ada spec RTW89_Tables_8852B with the five register tables the
driver loads: BB, BB gain, radio A, radio B and NCTL. The tables are data:
(address, data) pairs exactly as Realtek ships them, conditional headers
included; RTW89_PHY_Tables evaluates the conditions on the device.

Usage: generate_tables.py <rtw8852b_table.c> <output .ads>
       generate_tables.py --check <rtw8852b_table.c> <existing .ads>

The source's SHA-256 must be the pinned one: a different rtw89 revision is
a deliberate update (change PINNED_SHA256 and LINUX_COMMIT together).
"""
import hashlib
import re
import sys

LINUX_COMMIT = '17bb0e2f6c8043f70a693a5f3797471cbed354c8'
PINNED_SHA256 = 'bcee2f4357f6ada16c831f460edc5e00c5471a79333b606e36cfa0b630352d09'

# C array name -> Ada constant name.
TABLES = [
    ('rtw89_8852b_phy_bb_regs', 'BB_Registers'),
    ('rtw89_8852b_phy_bb_reg_gain', 'BB_Gain'),
    ('rtw89_8852b_phy_radioa_regs', 'Radio_A'),
    ('rtw89_8852b_phy_radiob_regs', 'Radio_B'),
    ('rtw89_8852b_phy_nctl_regs', 'NCTL'),
]

PAIR = re.compile(r'\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}')


def parse(source):
    tables = {}
    for c_name, _ in TABLES:
        start = re.search(r'static const struct rtw89_reg2_def ' + c_name + r'\[\] = \{', source)
        if not start:
            raise SystemExit('table %s not found' % c_name)
        end = source.index('};', start.end())
        tables[c_name] = [(int(a, 16), int(d, 16)) for a, d in PAIR.findall(source[start.end():end])]
        if not tables[c_name]:
            raise SystemExit('table %s is empty' % c_name)
    return tables


def ada_hex(value):
    text = '%08X' % value
    return '16#%s_%s#' % (text[:4], text[4:])


def render(tables):
    out = []
    out.append('-' * 78)
    out.append('--  GENERATED by userspace/services/rtw89/tools/generate_tables.py: do not')
    out.append('--  edit. Source: Linux drivers/net/wireless/realtek/rtw89/rtw8852b_table.c')
    out.append('--  at commit %s' % LINUX_COMMIT)
    out.append('--  (SHA-256 %s).' % PINNED_SHA256)
    out.append('--')
    out.append('--  Copyright(c) 2019-2020 Realtek Corporation. Used under the BSD-3-Clause')
    out.append('--  option of its GPL-2.0 OR BSD-3-Clause licence:')
    out.append('--')
    out.append('--  Redistribution and use in source and binary forms, with or without')
    out.append('--  modification, are permitted provided that the following conditions are met:')
    out.append('--  1. Redistributions of source code must retain the above copyright notice,')
    out.append('--     this list of conditions and the following disclaimer.')
    out.append('--  2. Redistributions in binary form must reproduce the above copyright')
    out.append('--     notice, this list of conditions and the following disclaimer in the')
    out.append('--     documentation and/or other materials provided with the distribution.')
    out.append('--  3. Neither the name of the copyright holder nor the names of its')
    out.append('--     contributors may be used to endorse or promote products derived from')
    out.append('--     this software without specific prior written permission.')
    out.append('--')
    out.append('--  THIS SOFTWARE IS PROVIDED BY THE COPYRIGHT HOLDERS AND CONTRIBUTORS "AS IS"')
    out.append('--  AND ANY EXPRESS OR IMPLIED WARRANTIES, INCLUDING, BUT NOT LIMITED TO, THE')
    out.append('--  IMPLIED WARRANTIES OF MERCHANTABILITY AND FITNESS FOR A PARTICULAR PURPOSE')
    out.append('--  ARE DISCLAIMED. IN NO EVENT SHALL THE COPYRIGHT HOLDER OR CONTRIBUTORS BE')
    out.append('--  LIABLE FOR ANY DIRECT, INDIRECT, INCIDENTAL, SPECIAL, EXEMPLARY, OR')
    out.append('--  CONSEQUENTIAL DAMAGES (INCLUDING, BUT NOT LIMITED TO, PROCUREMENT OF')
    out.append('--  SUBSTITUTE GOODS OR SERVICES; LOSS OF USE, DATA, OR PROFITS; OR BUSINESS')
    out.append('--  INTERRUPTION) HOWEVER CAUSED AND ON ANY THEORY OF LIABILITY, WHETHER IN')
    out.append('--  CONTRACT, STRICT LIABILITY, OR TORT (INCLUDING NEGLIGENCE OR OTHERWISE)')
    out.append('--  ARISING IN ANY WAY OUT OF THE USE OF THIS SOFTWARE, EVEN IF ADVISED OF THE')
    out.append('--  POSSIBILITY OF SUCH DAMAGE.')
    out.append('-' * 78)
    out.append('pragma Ada_2022;')
    out.append('with RTW89_PHY_Tables; use RTW89_PHY_Tables;')
    out.append('')
    out.append('package RTW89_Tables_8852B with Pure, SPARK_Mode is')
    for c_name, ada_name in TABLES:
        rows = tables[c_name]
        out.append('')
        out.append('   --  %s: %d entries.' % (c_name, len(rows)))
        out.append('   %s : constant Table (1 .. %d) :=' % (ada_name, len(rows)))
        body = ['(%s, %s)' % (ada_hex(a), ada_hex(d)) for a, d in rows]
        lines = []
        for i in range(0, len(body), 2):
            lines.append('      ' + ', '.join(body[i:i + 2]))
        out.append('     [' + ',\n'.join(lines).lstrip() + '];')
    out.append('')
    out.append('end RTW89_Tables_8852B;')
    return '\n'.join(out) + '\n'


def main(argv):
    check = len(argv) == 4 and argv[1] == '--check'
    if len(argv) != 3 and not check:
        raise SystemExit(__doc__)
    source_path, output_path = argv[-2], argv[-1]
    raw = open(source_path, 'rb').read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINNED_SHA256:
        raise SystemExit('%s: SHA-256 %s is not the pinned %s' % (source_path, digest, PINNED_SHA256))
    text = render(parse(raw.decode()))
    if check:
        if open(output_path).read() != text:
            print('FAIL: %s differs from a fresh generation' % output_path)
            return 1
        print('PASS: %s matches a fresh generation' % output_path)
        return 0
    open(output_path, 'w').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
