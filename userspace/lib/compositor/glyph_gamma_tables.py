#!/usr/bin/env python3
"""Generate the glyph coverage-correction tables (backlog UI-026).

Text is blended in sRGB values by every CuBit glyph path (toolkit, desktop
CPU compositor, Vulkan shader), which makes dark text heavy and light text
thin. Instead of decoding and re-encoding each destination pixel, each path
first maps a glyph's coverage through one 256-entry table chosen by the
ink's luminance. The table is solved so that the ordinary sRGB-value blend
then equals a blend in linear light against the assumed background (the
ink's perceptual inverse: light behind dark ink, dark behind light ink),
optionally with a contrast boost (zero now: the font engine darkens stems
itself). Skia/Chrome use the same
"preblend" scheme. The result is exact linear-light blending whenever the real
background is the assumed one, and needs no destination read, so the GPU path
(which blends in fixed function) gets the very same table.

Outputs (all checked in, all generated from this one definition):
  glyph_gamma.ads       Ada constant table (SPARK, Pure)
  vulkan_affine.frag    the block between the GLYPH-GAMMA markers
  tests/compositor/vulkan_affine_host.c   the hosted Vulkan oracle's copy

  python3 glyph_gamma_tables.py           rewrite every output
  python3 glyph_gamma_tables.py --check   fail if any output is stale
"""
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
BUCKETS = 16                  # ink-luminance classes
BUCKET_WIDTH = 256 // BUCKETS
# Rec. 709 luma weights in 1/256 (sum 256), applied to sRGB values as Skia does.
RED_WEIGHT, GREEN_WEIGHT, BLUE_WEIGHT = 54, 183, 19
# Contrast boost. DARK applies to dark ink on a light background and fades
# out toward light ink; LIGHT is the residual boost for light ink. Round 1
# used 0.8 / 0.3 as a stand-in for stem darkening; the font engine now
# emboldens outlines as FreeType does (userspace/rust/fonts, Darken), and any
# boost on top measures worse against FreeType (tests/ui-fonts/quality), so
# the tables are a plain linear-light preblend.
DARK_INK_CONTRAST = 0.0
LIGHT_INK_CONTRAST = 0.0


def to_linear(v):
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def to_srgb(v):
    v = min(1.0, max(0.0, v))
    return v * 12.92 if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055


def table(bucket):
    ink = (bucket * BUCKET_WIDTH + BUCKET_WIDTH // 2) / 255.0
    back = 1.0 - ink
    ink_l, back_l = to_linear(ink), to_linear(back)
    boost = DARK_INK_CONTRAST * back_l + LIGHT_INK_CONTRAST * (1.0 - back_l)
    row = []
    for i in range(256):
        a = i / 255.0
        a = a + (1.0 - a) * boost * a
        if abs(ink - back) < 1.0 / 256.0:
            result = a
        else:
            result = (to_srgb(ink_l * a + (1.0 - a) * back_l) - back) / (ink - back)
        row.append(min(255, max(0, round(result * 255.0))))
    row[0], row[255] = 0, 255
    for i in range(1, 256):          # monotone, so more ink never looks lighter
        row[i] = max(row[i], row[i - 1])
    return row


TABLES = [table(b) for b in range(BUCKETS)]


def ada():
    rows = []
    for b, row in enumerate(TABLES):
        lines = [", ".join(f"{v:3d}" for v in row[i:i + 16]) for i in range(0, 256, 16)]
        body = ",\n         ".join(lines)
        rows.append(f"      {b:2d} => [\n         {body}]")
    table_text = ",\n".join(rows)
    return f"""--  GENERATED by glyph_gamma_tables.py (UI-026); do not edit. Regenerate
--  with `python3 userspace/lib/compositor/glyph_gamma_tables.py`.
with Interfaces;

--  Glyph coverage correction: every glyph path maps coverage through one row
--  of Correction, chosen by the ink's luminance, before its usual sRGB-value
--  blend. The rows are solved so that blend equals a linear-light blend over
--  the ink's perceptual inverse (stems are darkened by the font engine, not
--  here). Exact when the real background is that inverse; no
--  destination read, so the Vulkan glyph shader uses the same rows.
package Glyph_Gamma with SPARK_Mode, Pure is
   use type Interfaces.Unsigned_32, Interfaces.Unsigned_8;
   subtype Byte is Interfaces.Unsigned_8;
   subtype Word is Interfaces.Unsigned_32;
   Buckets : constant := {BUCKETS};
   Bucket_Width : constant := 256 / Buckets;
   Red_Weight : constant := {RED_WEIGHT};
   Green_Weight : constant := {GREEN_WEIGHT};
   Blue_Weight : constant := {BLUE_WEIGHT};
   Weight_Total : constant := Red_Weight + Green_Weight + Blue_Weight;
   Channel_Last : constant := 255;
   subtype Bucket is Natural range 0 .. Buckets - 1;
   subtype Channel is Natural range 0 .. Channel_Last;

   function Red (Ink : Word) return Channel is
     (Channel (Interfaces.Shift_Right (Ink, 16) and Channel_Last));
   function Green (Ink : Word) return Channel is
     (Channel (Interfaces.Shift_Right (Ink, 8) and Channel_Last));
   function Blue (Ink : Word) return Channel is (Channel (Ink and Channel_Last));
   --  Luma of an RGB ink (alpha ignored), in 1/256, then its bucket.
   function Bucket_Of (Ink : Word) return Bucket is
     ((Red_Weight * Red (Ink) + Green_Weight * Green (Ink) + Blue_Weight * Blue (Ink))
        / Weight_Total / Bucket_Width);

   type Row is array (Byte) of Byte;
   type Table is array (Bucket) of Row;
   Correction : constant Table := [
{table_text}];

   --  No coverage stays none and full coverage stays full, in every row, so
   --  callers keep their skip-transparent and copy-opaque fast paths.
   function Keeps_Ends return Boolean is
     (for all B in Bucket => Correction (B) (0) = 0 and Correction (B) (Byte'Last) = Byte'Last)
     with Ghost;

   function Adjust (Ink_Row : Bucket; Coverage : Byte) return Byte is
     (Correction (Ink_Row) (Coverage))
     with Post => (if Coverage = 0 then Adjust'Result = 0) and
                  (if Coverage = Byte'Last then Adjust'Result = Byte'Last);
end Glyph_Gamma;
"""


def glsl():
    words = []
    for row in TABLES:
        for i in range(0, 256, 4):
            words.append(row[i] | row[i + 1] << 8 | row[i + 2] << 16 | row[i + 3] << 24)
    lines = [",".join(f"0x{w:08x}u" for w in words[i:i + 8]) for i in range(0, len(words), 8)]
    body = ",\n".join(lines)
    return (f"// GLYPH-GAMMA BEGIN (generated by glyph_gamma_tables.py; do not edit)\n"
            f"// Glyph_Gamma.Correction, four coverage bytes per word, row by ink bucket.\n"
            f"const uint glyph_gamma_buckets={BUCKETS}u;\n"
            f"const uvec3 glyph_gamma_weights=uvec3({RED_WEIGHT}u,{GREEN_WEIGHT}u,{BLUE_WEIGHT}u);\n"
            f"const uint glyph_gamma[{len(words)}]=uint[](\n{body});\n"
            f"// GLYPH-GAMMA END\n")


def c_oracle():
    rows = []
    for row in TABLES:
        lines = [",".join(str(v) for v in row[i:i + 32]) for i in range(0, 256, 32)]
        rows.append("    {" + ",\n     ".join(lines) + "}")
    body = ",\n".join(rows)
    return (f"/* GLYPH-GAMMA BEGIN (generated by glyph_gamma_tables.py; do not edit) */\n"
            f"static const unsigned char glyph_gamma[{BUCKETS}][256]={{\n{body}}};\n"
            f"static unsigned glyph_gamma_coverage(uint32_t ink,unsigned coverage)\n"
            f"{{\n    const unsigned luma=({RED_WEIGHT}u*((ink>>16)&255u)+{GREEN_WEIGHT}u*((ink>>8)&255u)+"
            f"{BLUE_WEIGHT}u*(ink&255u))/{RED_WEIGHT + GREEN_WEIGHT + BLUE_WEIGHT}u;\n"
            f"    return glyph_gamma[luma/{BUCKET_WIDTH}u][coverage&255u];\n}}\n"
            f"/* GLYPH-GAMMA END */\n")


def spliced(text, block, begin="// GLYPH-GAMMA BEGIN", end="// GLYPH-GAMMA END\n"):
    a, b = text.index(begin), text.index(end) + len(end)
    return text[:a] + block + text[b:]


def main():
    ads, frag = HERE / "glyph_gamma.ads", HERE / "vulkan_affine.frag"
    oracle = HERE.parents[2] / "tests/compositor/vulkan_affine_host.c"
    want = {ads: ada(), frag: spliced(frag.read_text(), glsl())}
    if oracle.exists():
        want[oracle] = spliced(oracle.read_text(), c_oracle(),
                               "/* GLYPH-GAMMA BEGIN", "/* GLYPH-GAMMA END */\n")
    if "--check" in sys.argv[1:]:
        stale = [p.name for p, t in want.items() if not p.exists() or p.read_text() != t]
        if stale:
            raise SystemExit("glyph gamma tables stale: " + ", ".join(stale))
        print("glyph gamma tables current")
        return
    for path, text in want.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print("wrote", path)


if __name__ == "__main__":
    main()
