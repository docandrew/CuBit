"""The desktop's application icons: the CuBit desktop icons
(assets/desktop-icons, made by its make.py) and Penny's own artwork
(assets/penny), 24-pixel straight-alpha, in Desktop_Icons.Icon_ID order.

This writes Desktop_Icons (the Icon_ID literals and ICON_SIZE). The pixels
are not compiled in: tools/build_icon_assets.py packs the same PNGs, in
this order, into Assets/cubit-icons/<version>/applications.qoi
(docs/assets.md), which Desktop loads at startup. Changing ICONS (order,
additions) changes the atlas layout: bump ICON_PACKAGE_VERSION here and
Desktop_Icon_Assets.Package_Path together.

Run from the repository root inside nix develop, after make.py:
  python3 tools/generate_desktop_icons.py
"""
