#!/usr/bin/env python3
"""Synthetic EDID fixtures for the display-modeset hosted tests.

Writes build/source/edid_fixtures.ads: byte-exact base + CTA-861 blocks with
correct checksums. The shapes follow real monitors (a 27" 4K HDMI 2.0 panel,
a 1080p eDP laptop panel, a DVI monitor) but no vendor's data is copied.
"""
import sys
from pathlib import Path


def checksum(block):
    block[127] = (-sum(block[:127])) & 0xFF
    return block


def dtd(clock_khz, w, hblank, hfront, hsync, h, vblank, vfront, vsync,
        w_mm, h_mm, hpos=True, vpos=True):
    c = clock_khz // 10
    d = [0] * 18
    d[0], d[1] = c & 0xFF, c >> 8
    d[2], d[3] = w & 0xFF, hblank & 0xFF
    d[4] = ((w >> 8) << 4) | (hblank >> 8)
    d[5], d[6] = h & 0xFF, vblank & 0xFF
    d[7] = ((h >> 8) << 4) | (vblank >> 8)
    d[8], d[9] = hfront & 0xFF, hsync & 0xFF
    d[10] = ((vfront & 15) << 4) | (vsync & 15)
    d[11] = ((hfront >> 8) << 6) | ((hsync >> 8) << 4) | ((vfront >> 4) << 2) | (vsync >> 4)
    d[12], d[13] = w_mm & 0xFF, h_mm & 0xFF
    d[14] = ((w_mm >> 8) << 4) | (h_mm >> 8)
    d[17] = 0x18 | (4 if vpos else 0) | (2 if hpos else 0)
    return d


def text_descriptor(tag, text):
    d = [0, 0, 0, tag, 0]
    body = list(text.encode()[:13])
    if len(body) < 13:
        body += [0x0A] + [0x20] * (12 - len(body))
    return d + body


def range_limits(max_clock_mhz):
    return [0, 0, 0, 0xFD, 0, 24, 75, 30, 160, max_clock_mhz // 10, 0, 0x0A] + [0x20] * 6


def base_block(vendor, product, serial, cm, descriptors, extensions):
    b = [0] * 128
    b[0:8] = [0, 255, 255, 255, 255, 255, 255, 0]
    code = sum((ord(ch) - 64) << (10 - 5 * i) for i, ch in enumerate(vendor))
    b[8], b[9] = code >> 8, code & 0xFF
    b[10], b[11] = product & 0xFF, product >> 8
    b[12:16] = list(serial.to_bytes(4, "little"))
    b[16], b[17] = 12, 2023 - 1990
    b[18], b[19] = 1, 4
    b[20] = 0xA5  # digital, 10 bpc, DisplayPort/HDMI-ish (not decoded)
    b[21], b[22] = cm
    b[24] = 0x0A  # preferred timing includes native format
    for i, d in enumerate(descriptors):
        b[54 + 18 * i:72 + 18 * i] = d
    for i in range(len(descriptors), 4):
        b[54 + 18 * i:72 + 18 * i] = [0, 0, 0, 0x10] + [0] * 14
    b[126] = extensions
    return checksum(b)


def cta_block(data_blocks, dtds):
    e = [0] * 128
    e[0], e[1] = 0x02, 3
    body = []
    for tag, payload in data_blocks:
        body += [(tag << 5) | len(payload)] + payload
    e[2] = 4 + len(body)
    e[3] = 0x70
    e[4:4 + len(body)] = body
    at = e[2]
    for d in dtds:
        e[at:at + 18] = d
        at += 18
    return checksum(e)


UHD60 = dtd(594000, 3840, 560, 176, 88, 2160, 90, 8, 10, 597, 336)
UHD30 = dtd(297000, 3840, 560, 176, 88, 2160, 90, 8, 10, 597, 336)
FHD60 = dtd(148500, 1920, 280, 88, 44, 1080, 45, 4, 5, 597, 336)
QHD60 = dtd(241500, 2560, 160, 48, 32, 1440, 41, 3, 5, 597, 336, vpos=False)

FIXTURES = {
    # 27" 4K HDMI 2.0 monitor: 4K60 preferred, HF-VSDB 600 MHz with SCDC.
    "UHD_HDMI": [
        base_block("CUB", 0x2701, 0x00C0FFEE, (60, 34),
                   [UHD60, text_descriptor(0xFC, "CuBit UHD27"),
                    range_limits(600), UHD30], 1),
        cta_block([(2, [16 + 128, 97, 95, 4, 31, 3, 1]),
                   (3, [0x03, 0x0C, 0x00, 0x10, 0x00, 0x38, 68]),
                   (3, [0xD8, 0x5D, 0xC4, 0x01, 120, 0x80])],
                  [FHD60, QHD60]),
    ],
    # The same monitor without an HDMI Forum block: an HDMI 1.4 sink (340 MHz).
    "UHD_HDMI14": [
        base_block("CUB", 0x2702, 7, (60, 34),
                   [UHD30, text_descriptor(0xFC, "CuBit UHD14"), FHD60], 1),
        cta_block([(2, [97, 95, 16]), (3, [0x03, 0x0C, 0x00, 0x10, 0x00, 0x38, 68])], []),
    ],
    # 14" 1080p eDP laptop panel: one DTD, no extensions.
    "FHD_EDP": [
        base_block("CUB", 0x1401, 0, (31, 17),
                   [dtd(138700, 1920, 160, 48, 32, 1080, 30, 3, 6, 309, 174, vpos=False),
                    text_descriptor(0xFE, "CUBIT PANEL")], 0),
    ],
    # DVI monitor (no HDMI vendor block), name with padding.
    "DVI_1080": [
        base_block("ABC", 0x0101, 1, (53, 30),
                   [FHD60, text_descriptor(0xFC, "Old  ")], 1),
        cta_block([(2, [16, 4])], []),
    ],
}


def main():
    out = Path(sys.argv[1])
    lines = ["--  Generated by tests/display-modeset/edid_fixtures.py; do not edit.",
             "with CuBit.Monitor_EDID.Catalog;",
             "package EDID_Fixtures is",
             "   package C renames CuBit.Monitor_EDID.Catalog;"]
    for name, blocks in FIXTURES.items():
        lines.append(f"   {name}_Base : constant C.Block :=")
        lines.append("     [" + ", ".join(str(b) for b in blocks[0]) + "];")
        ext = blocks[1:]
        if ext:
            rows = ",\n      ".join("[" + ", ".join(str(b) for b in e) + "]" for e in ext)
            lines.append(f"   {name}_Extensions : constant C.Block_Array (1 .. {len(ext)}) :=")
            lines.append(f"     [{'1 => ' if len(ext) == 1 else ''}{rows}];")
        else:
            lines.append(f"   {name}_Extensions : constant C.Block_Array (1 .. 0) := [];")
    lines.append("end EDID_Fixtures;")
    out.write_text("\n".join(lines) + "\n")
    raw = out.with_suffix(".bin.d")
    raw.mkdir(exist_ok=True)
    for name, blocks in FIXTURES.items():
        (raw / f"{name.lower()}.bin").write_bytes(bytes(sum(blocks, [])))


if __name__ == "__main__":
    main()
